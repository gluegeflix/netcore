################################################################################
# Quiet Command Helper
################################################################################

run_command_quiet() {

    local DESCRIPTION="$1"
    shift

    log_info "$DESCRIPTION"

    if [[ "$DRY_RUN" == true ]]; then
        log_warn "[DRY RUN] $*"
        return 0
    fi

    local TEMP_OUTPUT
    TEMP_OUTPUT=$(mktemp)

    if "$@" >"$TEMP_OUTPUT" 2>&1; then

        if [[ -n "${LOG_FILE:-}" ]]; then
            cat "$TEMP_OUTPUT" >> "$LOG_FILE"
        fi

        if [[ "$VERBOSE" == true ]]; then
            cat "$TEMP_OUTPUT"
        fi

        rm -f "$TEMP_OUTPUT"
        log_success "$DESCRIPTION"
        return 0

    else

        local RESULT=$?

        if [[ -n "${LOG_FILE:-}" ]]; then
            cat "$TEMP_OUTPUT" >> "$LOG_FILE"
        fi

        cat "$TEMP_OUTPUT" >&2
        rm -f "$TEMP_OUTPUT"

        log_error "Command failed: $*"
        return "$RESULT"

    fi

}


